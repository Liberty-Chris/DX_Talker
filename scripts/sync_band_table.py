"""Compile WB4IUY's authoritative DXt selection policy for both platforms.

Keep the supplied CSV unchanged. kHz columns define exact boundaries; MHz
columns are display references. This is distinct from emission authorizations.
"""
import csv
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'docs/reference/band_table.csv'
rows = [r for r in csv.reader(source.read_text(encoding='utf-8-sig').splitlines()) if r][1:]
rules = sorted({(r[8], m.strip(), r[2], r[3], 'point' if r[6] == 'Discrete reported frequency' else 'range', r[9])
                for r in rows if r[0] == 'License filter' for m in r[7].split(';')})
inference = [(r[2], r[3], r[7]) for r in rows if r[0] == 'Mode inference' and r[7] != 'Unknown']
digest = hashlib.sha256(source.read_bytes()).hexdigest()
py = '# Generated by scripts/sync_band_table.py. Do not edit.\n'
py += f'SOURCE_SHA256 = {digest!r}\nRULES = (\n'
py += ''.join(f'    {r!r},\n' for r in rules) + ')\n'
py += 'INFERENCE = ' + repr(tuple(inference)) + '\n'
kt = '// Generated by scripts/sync_band_table.py. Do not edit.\npackage club.dxtalker.android\n\ninternal object BandTableData {\n'
kt += f'    const val sourceSha256 = "{digest}"\n'
# Split by class so generated JVM methods and constant pool strings stay bounded.
kt += '    val rules: List<List<String>> = listOf(\n'
for cls in sorted({r[0] for r in rules}):
    kt += '        ' + cls.lower() + '(),\n'
kt += '    ).flatten()\n'
for cls in sorted({r[0] for r in rules}):
    kt += '    private fun ' + cls.lower() + '() = """' + '\n'.join('|'.join(r) for r in rules if r[0] == cls) + '""".lines().map { it.split(\'|\') }\n'
kt += '    val inference = listOf(' + ','.join('Triple("' + lo + '".toBigDecimal(),"' + hi + '".toBigDecimal(),"' + mode + '")' for lo,hi,mode in inference) + ')\n'
kt += '}\n'
targets = {ROOT / 'dxtalker/band_table_data.py': py,
           ROOT / 'android/app/src/main/java/club/dxtalker/android/BandTableData.kt': kt}
for path, text in targets.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != text: raise SystemExit('Run scripts/sync_band_table.py')
    else: path.write_text(text)
print('Authoritative band table:', len(rules), 'mode/class rules;', len(inference), 'inference segments')
