"""Generate Kotlin's frequency tables from the reviewed Python rule data."""
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from dxtalker.privileges import ALLOCATIONS,VHF,DATA,PHONE,RULES_VERSION
root=Path(__file__).resolve().parents[1]
lines=['// Generated by scripts/sync_privileges.py. Do not edit tables by hand.','package club.dxtalker.android','', 'internal object UsPrivilegeData {',f'    const val version = "{RULES_VERSION}"']
for name,spans in [('vhf',VHF),('data',DATA),('phone',PHONE)]:
    lines.append(f'    val {name} = ranges("'+ ';'.join(str(lo)+','+str(hi) for lo,hi in spans)+'")')
lines.append('    val allocations = mapOf(')
for name,spans in ALLOCATIONS.items():lines.append('        "'+name+'" to ranges("'+';'.join(str(lo)+','+str(hi) for lo,hi in spans)+'"),')
lines += ['    )','    private fun ranges(value:String) = value.split(\';\').map { val p=it.split(\',\');p[0].toBigDecimal() to p[1].toBigDecimal() }','}']
text='\n'.join(lines)+'\n';path=root/'android/app/src/main/java/club/dxtalker/android/UsPrivilegeData.kt'
if '--check' in sys.argv:
    if not path.exists() or path.read_text()!=text:raise SystemExit('Kotlin license tables need scripts/sync_privileges.py')
else:path.write_text(text)
